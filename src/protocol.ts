/**
 * Shared wire contract between the two halves of dsh-prompt-forge.
 *
 * The host half owns the LLM channel: the browser never sees an API key, a
 * base URL, or the provider SDK — it posts a draft to a loopback route and
 * reads a server-sent event stream back. Everything both halves must agree on
 * (route paths, request/response shapes, limits) lives here.
 */

/**
 * Settings namespace the host half registers, as declared in cordis.patch.yml.
 *
 * The managed-forms settings provider keys every namespace by Loader entry id,
 * and an **inserted** row's entry id is `include:<rowId>`. So this plugin's
 * live namespace is `include:prompt-forge`, not this bare value: the
 * constant names the row, and the browser half resolves the concrete string at
 * runtime (exact id → `:<rowId>` suffix → schema fingerprint). Keeping the row
 * id and this constant identical is what makes that resolution unambiguous.
 */
export const PROMPT_FORGE_NAMESPACE = 'prompt-forge'

/**
 * Field names unique to this plugin's Config, used to recognize its settings
 * section if the entry id ever stops matching {@link PROMPT_FORGE_NAMESPACE}
 * (a renamed patch row, or a host that keys sections differently).
 */
export const CONFIG_FINGERPRINT_FIELDS = ['mainSystemPrompt', 'activePresetId'] as const

/** Route family, all loopback-fenced same-origin POST/GET endpoints. */
export const OPTIMIZER_API = {
  /** GET: the configured provider roster with each route's model catalog. */
  models: '/api/dsh-prompt-forge/models',
  /** POST: one optimization run, answered as an SSE stream. */
  optimize: '/api/dsh-prompt-forge/optimize',
} as const

/**
 * Default model route. `ofox` is the provider id the desktop profile declares;
 * the model is the flash tier, which is fast enough for interactive rewriting.
 */
export const DEFAULT_PROVIDER = 'ofox'
export const DEFAULT_MODEL = 'deepseek/deepseek-v4.1-flash'

/** Default sampling temperature: low, because rewriting must not invent intent. */
export const DEFAULT_TEMPERATURE = 0.3

/**
 * Draft length ceiling. The route refuses anything longer instead of silently
 * truncating: a user who pasted a whole file deserves a readable refusal.
 */
export const MAX_DRAFT_CHARS = 20000

/** One optimization request body. */
export interface OptimizeRequest {
  /** The draft to rewrite. */
  text: string
  /**
   * System prompt to apply. The browser resolves preset-vs-main copy and sends
   * the final string, so the host never has to re-derive plugin settings.
   */
  system: string
  /** Previous optimized version, when the user asked for a follow-up tweak. */
  previous?: string
  /** Free-form follow-up instruction ("make it shorter", "add error handling"). */
  instruction?: string
}

/** One provider route and the models it currently advertises. */
export interface ProviderModelGroup {
  /** Provider route id passed back as `provider` (e.g. `ofox`). */
  id: string
  /** Human-facing provider name. */
  name: string
  /** Advertised chat models, already filtered and sorted. */
  models: Array<{ id: string; name: string }>
}

/** GET /models answer. */
export interface ModelsResponse {
  ok: boolean
  providers?: ProviderModelGroup[]
  code?: string
  message?: string
}

/** One SSE frame the optimize route emits. */
export type OptimizeEvent =
  /** A run started; carries the route actually used. */
  | { type: 'start'; provider: string; model: string }
  /** Visible text delta, appended verbatim to the result pane. */
  | { type: 'delta'; text: string }
  /** Terminal success. */
  | { type: 'done'; text: string; aborted?: boolean }
  /** Terminal failure with a human-readable reason. */
  | { type: 'error'; code: string; message: string }

/** One optimization preset: a named system prompt. */
export interface OptimizerPreset {
  /** Stable id; generated by the settings page, never reused. */
  id: string
  /** Display name shown in the dialog's preset selector. */
  name: string
  /** The system prompt this preset applies. */
  system: string
}

/** Settings shape this plugin's namespace stores. */
export interface OptimizerConfig {
  /** Master switch: hides the composer button and refuses both routes. */
  enabled?: boolean
  /** Provider route id (a `ctx.llm` provider key). */
  provider?: string
  /** Model id inside that provider. */
  model?: string
  /** Sampling temperature. */
  temperature?: number
  /** Output token ceiling; 0 or unset leaves the model default. */
  maxTokens?: number
  /** The prompt applied when no preset is selected. */
  mainSystemPrompt?: string
  /** Named alternative system prompts. */
  presets?: OptimizerPreset[]
  /** Selected preset id, or empty to use {@link mainSystemPrompt}. */
  activePresetId?: string
}
